def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    el = OxmlElement('w:shd')
    el.set(qn('w:val'), 'clear'); el.set(qn('w:color'), 'auto'); el.set(qn('w:fill'), hexcolor)
    tcPr.append(el)


def table(headers, rows, widths=None):
    """行=纵向（自上而下）、列=横向（自左而右）"""
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, htxt in enumerate(headers):
        hdr[i].text = ''
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.line_spacing = 1.15
        _fix_font(p.add_run(htxt), 9, True)
        shade(hdr[i], 'F2F2F2')
    for r in rows:
        cells = t.add_row().cells
        for i, val in enumerate(r):
            cells[i].text = ''
            p = cells[i].paragraphs[0]
            p.paragraph_format.line_spacing = 1.15
            if i == 0:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            col = INK
            sv = str(val)
            if sv.startswith('↑') or sv.startswith('+') and '%' in sv and not sv.startswith('+-'):
                col = RED
            elif sv.startswith('↓') or sv.startswith('-') and '%' in sv:
                col = GREEN
            _fix_font(p.add_run(str(val)), 9, False, col)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    return t


def spacer(pt=6):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(pt)
    _fix_font(p.add_run(''), 6)
    return p


